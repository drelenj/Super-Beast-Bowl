// Builds data/tech_ratings.json and docs/TECH_POPULATION_REPORT.md from data/rosters.json.
// ARCADE-DERIVED, NOT CANON (tech-1.0). Run: npm run build:tech  (or: npx tsx scripts/build_tech.ts)
// Deterministic: no timestamps, so re-running on the same roster rewrites byte-identical files.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import type { PlayerData, PhysRatings, PosCode } from '../src/engine/types';
import { buildTechExport, ROLE_SKILLS, TECH_KEYS, TECH_LABEL, TECH_VERSION, techComposite, techNoise, techRatings } from '../src/ratings/tech';

const path = (rel: string): string => fileURLToPath(new URL(rel, import.meta.url));
interface Team { franchise: string; players: PlayerData[] }
const rosters = JSON.parse(readFileSync(path('../data/rosters.json'), 'utf8')) as { teams: Team[] };
const teams = rosters.teams;
const all = teams.flatMap((t) => t.players);

// ---- stats helpers ----
const mean = (a: number[]): number => (a.length ? a.reduce((s, x) => s + x, 0) / a.length : NaN);
const sd = (a: number[]): number => { if (a.length < 2) return NaN; const m = mean(a); return Math.sqrt(a.reduce((s, x) => s + (x - m) * (x - m), 0) / (a.length - 1)); };
function pearson(x: number[], y: number[]): number {
  const mx = mean(x), my = mean(y); let sxy = 0, sxx = 0, syy = 0;
  for (let i = 0; i < x.length; i++) { const dx = x[i] - mx, dy = y[i] - my; sxy += dx * dy; sxx += dx * dx; syy += dy * dy; }
  return sxy / Math.sqrt(sxx * syy);
}
function ranks(a: number[]): number[] {
  const idx = a.map((v, i) => [v, i] as [number, number]).sort((p, q) => p[0] - q[0]);
  const r = new Array<number>(a.length); let i = 0;
  while (i < idx.length) { let j = i; while (j + 1 < idx.length && idx[j + 1][0] === idx[i][0]) j++; const rk = (i + j) / 2 + 1; for (let k = i; k <= j; k++) r[idx[k][1]] = rk; i = j + 1; }
  return r;
}
const spearman = (x: number[], y: number[]): number => pearson(ranks(x), ranks(y));
const f1 = (v: number): string => (Number.isFinite(v) ? v.toFixed(1) : '-');
const f2 = (v: number): string => (Number.isFinite(v) ? v.toFixed(2) : '-');
const f3 = (v: number): string => (Number.isFinite(v) ? v.toFixed(3) : '-');

// ---- 1. data/tech_ratings.json ----
const out = buildTechExport(teams);
writeFileSync(path('../data/tech_ratings.json'), JSON.stringify(out, null, 1) + '\n');

// ---- 2. docs/TECH_POPULATION_REPORT.md ----
const POS: PosCode[] = ['STR', 'SCT', 'SEN', 'TRK', 'HNT', 'TRP', 'GRD', 'PDR', 'PFD', 'KPR', 'ARC'];
const PHYS: (keyof PhysRatings)[] = ['speed', 'strength', 'jumping', 'acceleration', 'agility', 'balance', 'throwPower', 'stamina', 'durability'];
const BANDS: [number, number][] = [[60, 69], [70, 79], [80, 89], [90, 99]];
const tech = new Map(all.map((p) => [p.id, techRatings(p)]));
const comp = new Map(all.map((p) => [p.id, techComposite(p)]));
const T = (p: PlayerData) => tech.get(p.id)!;
const C = (p: PlayerData) => comp.get(p.id)!;
const SHORT: Record<string, string> = { tackling: 'tck', ballSecurity: 'sec', catching: 'cat', passAccuracy: 'pAc', passVision: 'pVi', shotAccuracy: 'sht', carryPower: 'car', elusiveness: 'elu', pursuit: 'pur', coverage: 'cov', screening: 'scr', archeryAim: 'aAim', archeryDiscipline: 'aDis', keeperReaction: 'kRe', keeperPositioning: 'kPo', footwork: 'ftw', discipline: 'dis', clutch: 'clu', awareness: 'awr' };

const L: string[] = [];
L.push(`# Technical ratings population report (${TECH_VERSION})`, '');
L.push(`**${TECH_LABEL} (${TECH_VERSION}).** Generated by \`scripts/build_tech.ts\` from \`data/rosters.json\`; do not edit by hand. Regenerate with \`npm run build:tech\`.`, '');
L.push(`Population: ${all.length} players, ${teams.length} teams. Technical ratings are integers 60-99. Composite = weighted mean of a position's 3 primary (weight 2) and 4 secondary (weight 1) skills. SD is the sample standard deviation (n-1).`, '');

L.push('## 1. Summary by position', '');
L.push('| Pos | n | Mean OVR | Mean composite | SD composite | Mean (composite - OVR) | Primary skills (mean) | Secondary skills (mean) |', '|---|---:|---:|---:|---:|---:|---|---|');
for (const pos of POS) {
  const ps = all.filter((p) => p.pos === pos); const r = ROLE_SKILLS[pos];
  const sk = (ks: (keyof typeof SHORT)[]) => ks.map((k) => `${k} ${f1(mean(ps.map((p) => T(p)[k as keyof ReturnType<typeof T>])))}`).join(', ');
  L.push(`| ${pos} | ${ps.length} | ${f1(mean(ps.map((p) => p.ovr)))} | ${f1(mean(ps.map(C)))} | ${f2(sd(ps.map(C)))} | ${f2(mean(ps.map((p) => C(p) - p.ovr)))} | ${sk(r.primary)} | ${sk(r.secondary)} |`);
}
L.push(`| ALL | ${all.length} | ${f1(mean(all.map((p) => p.ovr)))} | ${f1(mean(all.map(C)))} | ${f2(sd(all.map(C)))} | ${f2(mean(all.map((p) => C(p) - p.ovr)))} | | |`, '');

const skillTable = (title: string, groups: [string, PlayerData[]][]): void => {
  L.push(title, '');
  L.push(`| Group | n | OVR | ${TECH_KEYS.map((k) => SHORT[k]).join(' | ')} | comp | SD comp |`, `|---|---:|---:|${TECH_KEYS.map(() => '---:').join('|')}|---:|---:|`);
  for (const [name, ps] of groups) {
    if (!ps.length) { L.push(`| ${name} | 0 | - | ${TECH_KEYS.map(() => '-').join(' | ')} | - | - |`); continue; }
    L.push(`| ${name} | ${ps.length} | ${f1(mean(ps.map((p) => p.ovr)))} | ${TECH_KEYS.map((k) => f1(mean(ps.map((p) => T(p)[k])))).join(' | ')} | ${f1(mean(ps.map(C)))} | ${f2(sd(ps.map(C)))} |`);
  }
  L.push('');
};
L.push(`Column key: ${TECH_KEYS.map((k) => `${SHORT[k]} = ${k}`).join(', ')}.`, '');
skillTable('## 2. Mean of every skill by position', POS.map((pos) => [pos, all.filter((p) => p.pos === pos)]));
skillTable('## 3. Mean of every skill by OVR band', BANDS.map(([lo, hi]) => [`OVR ${lo}-${hi}`, all.filter((p) => p.ovr >= lo && p.ovr <= hi)]));

L.push('## 4. Composite by position and OVR band (mean, n)', '');
L.push(`| Pos | ${BANDS.map(([lo, hi]) => `${lo}-${hi}`).join(' | ')} |`, `|---|${BANDS.map(() => '---:').join('|')}|`);
for (const pos of POS) L.push(`| ${pos} | ${BANDS.map(([lo, hi]) => { const ps = all.filter((p) => p.pos === pos && p.ovr >= lo && p.ovr <= hi); return ps.length ? `${f1(mean(ps.map(C)))} (${ps.length})` : '-'; }).join(' | ')} |`);
L.push('');

L.push('## 5. Spread of each skill (whole population)', '');
L.push('| Skill | Mean | SD | Min | Max | At floor 60 | At ceiling 99 |', '|---|---:|---:|---:|---:|---:|---:|');
for (const k of TECH_KEYS) { const v = all.map((p) => T(p)[k]); L.push(`| ${k} | ${f1(mean(v))} | ${f2(sd(v))} | ${Math.min(...v)} | ${Math.max(...v)} | ${v.filter((x) => x === 60).length} | ${v.filter((x) => x === 99).length} |`); }
L.push('');

L.push('## 6. Correlations (Pearson, per player)', '');
const rOvr = pearson(all.map(C), all.map((p) => p.ovr));
L.push(`corr(composite, OVR), all ${all.length} players: **${f3(rOvr)}**`, '');
L.push('| Pos | n | corr(composite, OVR) |', '|---|---:|---:|');
for (const pos of POS) { const ps = all.filter((p) => p.pos === pos); L.push(`| ${pos} | ${ps.length} | ${f3(pearson(ps.map(C), ps.map((p) => p.ovr)))} |`); }
L.push('');
L.push('corr(composite, each physical rating) and, for reference, corr(OVR, the same physical rating). OVR is the best single predictor of the composite:', '');
L.push('| Predictor | corr with composite | corr with OVR |', '|---|---:|---:|');
L.push(`| OVR | ${f3(rOvr)} | 1.000 |`);
for (const k of PHYS) L.push(`| ${k} | ${f3(pearson(all.map(C), all.map((p) => p.phys[k])))} | ${f3(pearson(all.map((p) => p.ovr), all.map((p) => p.phys[k])))} |`);
L.push('');

L.push('## 7. Team strength order', '');
const starters = (t: Team) => t.players.filter((p) => p.role === 'Projected starter');
const tOvr = teams.map((t) => mean(starters(t).map((p) => p.ovr)));
const tComp = teams.map((t) => mean(starters(t).map(C)));
L.push(`Team strength = mean composite of the 12 'Projected starter' players. Spearman rank correlation with mean starter OVR over ${teams.length} teams: **${f3(spearman(tComp, tOvr))}** (Pearson ${f3(pearson(tComp, tOvr))}).`, '');
L.push('| Rank by OVR | Franchise | Mean starter OVR | Mean starter composite | Rank by composite |', '|---:|---|---:|---:|---:|');
const rkO = ranks(tOvr.map((v) => -v)), rkC = ranks(tComp.map((v) => -v));
teams.map((t, i) => i).sort((a, b) => tOvr[b] - tOvr[a]).forEach((i) => L.push(`| ${rkO[i]} | ${teams[i].franchise} | ${f2(tOvr[i])} | ${f2(tComp[i])} | ${rkC[i]} |`));
L.push('');

L.push('## 8. Noise and distinguishability', '');
const noise = all.flatMap((p) => TECH_KEYS.map((k) => techNoise(p.id, k)));
L.push(`Noise draws (${noise.length} = players x skills): mean ${f3(mean(noise))}, SD ${f3(sd(noise))}, min ${f2(Math.min(...noise))}, max ${f2(Math.max(...noise))} rating points.`, '');
let pairs = 0, ok3 = 0, identical = 0, sumDiff = 0;
const groups = new Map<string, PlayerData[]>();
for (const p of all) { const g = `${p.pos}|${p.ovr}`; if (!groups.has(g)) groups.set(g, []); groups.get(g)!.push(p); }
for (const g of groups.values()) for (let i = 0; i < g.length; i++) for (let j = i + 1; j < g.length; j++) {
  const a = T(g[i]), b = T(g[j]); let d = 0; for (const k of TECH_KEYS) if (a[k] !== b[k]) d++;
  pairs++; sumDiff += d; if (d >= 3) ok3++; if (d === 0) identical++;
}
L.push(`Pairs of players sharing position and OVR: ${pairs}. Pairs differing in at least 3 of 19 skills: ${ok3} (${f2((100 * ok3) / pairs)}%). Identical pairs: ${identical}. Mean number of differing skills per pair: ${f2(sumDiff / pairs)}.`, '');

writeFileSync(path('../docs/TECH_POPULATION_REPORT.md'), L.join('\n'));

console.log(`tech ${TECH_VERSION}: ${out.count} players -> data/tech_ratings.json, docs/TECH_POPULATION_REPORT.md`);
console.log(`corr(composite, OVR) = ${f3(rOvr)}; team Spearman = ${f3(spearman(tComp, tOvr))}; distinguishable pairs = ${f2((100 * ok3) / pairs)}% of ${pairs}`);
